# Prepares a minimal libobs SDK for building the OBS plugin, without building OBS:
#   - libobs headers from the obs-studio sources at the tag of the installed OBS;
#   - obs.lib, an import library generated from the exports of the installed obs.dll.
#
# Result: .deps\obs-sdk\{include,lib\obs.lib,version.txt}. CMake picks it up through
# OBS_SDK_DIR (default .deps\obs-sdk). A real libobs CMake package (libobs_DIR, e.g.
# from obs-plugintemplate's .deps) takes priority when it is given.
#
#   powershell -ExecutionPolicy Bypass -File tools\obs-sdk.ps1
#   powershell -ExecutionPolicy Bypass -File tools\obs-sdk.ps1 -ObsDir "D:\OBS" -Version 32.2.2

param(
    [string]$ObsDir,    # OBS install folder; default from HKLM\SOFTWARE\OBS Studio
    [string]$Version,   # obs-studio tag; default is the version of the installed obs.dll
    [string]$OutDir
)

$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
if (-not $OutDir) { $OutDir = Join-Path $root '.deps\obs-sdk' }

if (-not $ObsDir) {
    $ObsDir = (Get-ItemProperty 'HKLM:\SOFTWARE\OBS Studio' -ErrorAction SilentlyContinue).'(default)'
    if (-not $ObsDir) { throw 'OBS Studio is not installed (no HKLM\SOFTWARE\OBS Studio). Pass -ObsDir.' }
}
$obsDll = Join-Path $ObsDir 'bin\64bit\obs.dll'
if (-not (Test-Path $obsDll)) { throw "obs.dll not found: $obsDll" }
if (-not $Version) { $Version = (Get-Item $obsDll).VersionInfo.ProductVersion.Trim() }
Write-Host "OBS $Version at $ObsDir"

# ── Headers ──────────────────────────────────────────────────────────────────
$src = Join-Path $root ".deps\obs-studio-$Version"
if (-not (Test-Path (Join-Path $src 'libobs\obs-module.h'))) {
    if (Test-Path $src) { Remove-Item $src -Recurse -Force }
    git -c advice.detachedHead=false clone --quiet --depth 1 --branch $Version --filter=blob:none --sparse `
        https://github.com/obsproject/obs-studio $src
    if ($LASTEXITCODE) { throw "git clone of obs-studio $Version failed" }
    git -C $src sparse-checkout set libobs
    if ($LASTEXITCODE) { throw 'git sparse-checkout failed' }
}

$inc = Join-Path $OutDir 'include'
if (Test-Path $OutDir) { Remove-Item $OutDir -Recurse -Force }
New-Item -ItemType Directory -Force $inc | Out-Null
$libobs = Join-Path $src 'libobs'
Get-ChildItem $libobs -Recurse -Include *.h, *.hpp | ForEach-Object {
    $rel = $_.FullName.Substring($libobs.Length + 1)
    $dst = Join-Path $inc $rel
    New-Item -ItemType Directory -Force (Split-Path $dst) | Out-Null
    Copy-Item $_.FullName $dst
}
# Generated by the OBS build from obsconfig.h.in; plugins only need the release flags
@'
#pragma once

#define OBS_RELEASE_CANDIDATE 0
#define OBS_BETA 0
'@ | Set-Content -Encoding ascii (Join-Path $inc 'obsconfig.h')

# ── Import library ───────────────────────────────────────────────────────────
$vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio\Installer\vswhere.exe'
$vs = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
if (-not $vs) { throw 'Visual Studio with the C++ x64 tools is not installed' }
$msvc = Get-ChildItem (Join-Path $vs 'VC\Tools\MSVC') | Sort-Object Name -Descending | Select-Object -First 1
$bin = Join-Path $msvc.FullName 'bin\Hostx64\x64'

$lib = Join-Path $OutDir 'lib'
New-Item -ItemType Directory -Force $lib | Out-Null
$exports = & (Join-Path $bin 'dumpbin.exe') /nologo /exports $obsDll
if ($LASTEXITCODE) { throw 'dumpbin failed' }
# Export table rows: ordinal, hint, RVA, name
$names = $exports | ForEach-Object {
    if ($_ -match '^\s+\d+\s+[0-9A-F]+\s+[0-9A-F]{8}\s+(\S+)') { $Matches[1] }
}
if (-not $names) { throw 'No exports found in obs.dll' }
$def = Join-Path $lib 'obs.def'
(@('LIBRARY obs.dll', 'EXPORTS') + ($names | ForEach-Object { "    $_" })) | Set-Content -Encoding ascii $def
& (Join-Path $bin 'lib.exe') /nologo /machine:x64 "/def:$def" "/out:$(Join-Path $lib 'obs.lib')" | Out-Null
if ($LASTEXITCODE) { throw 'lib.exe failed' }
Remove-Item (Join-Path $lib 'obs.exp') -ErrorAction SilentlyContinue

Set-Content -Encoding ascii (Join-Path $OutDir 'version.txt') $Version
Write-Host "libobs SDK ready: $OutDir ($($names.Count) exports)"
